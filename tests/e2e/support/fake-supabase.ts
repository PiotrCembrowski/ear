function userIdFrom(request: http.IncomingMessage): string | null {
  const token = (request.headers.authorization ?? "").replace(/^Bearer\s+/i, "");
  try {
    const payload = JSON.parse(Buffer.from(token.split(".")[1] ?? "", "base64url").toString("utf8")) as { sub?: string };
    return payload.sub ?? null;
  } catch {
    return null;
  }
}

export function startFakeSupabase(port = FAKE_SUPABASE_PORT): http.Server {
  let log: string[] = [];
  const files = new Map<string, Buffer>();

  const server = http.createServer((request, response) => {
    const chunks: Buffer[] = [];
    request.on("data", (chunk: Buffer) => chunks.push(chunk));
    request.on("end", () => {
      const raw = Buffer.concat(chunks);
      const body = raw.toString("utf8");
      const url = new URL(request.url ?? "/", "http://fake");
      const path = url.pathname;
      const method = request.method ?? "GET";
      const single = (request.headers.accept ?? "").includes("vnd.pgrst.object");
      response.setHeader("access-control-allow-origin", "*");
      response.setHeader("access-control-allow-headers", "*");
      response.setHeader("access-control-allow-methods", "GET,POST,PUT,DELETE,PATCH,OPTIONS");
      const send = (data: unknown, status = 200, count?: number) => {
        response.statusCode = status;
        response.setHeader("content-type", "application/json");
        if (count !== undefined) response.setHeader("content-range", `0-${Math.max(0, count - 1)}/${count}`);
        response.end(JSON.stringify(data));
      };
      if (method === "OPTIONS") return send({}, 204);

      // Test controls
      if (path === "/__log") return send(log);
      if (path === "/__reset") {
        log = [];
        files.clear();
        return send({ ok: true });
      }

      // Auth: getClaims() with symmetric keys verifies the token here.
      if (path === "/auth/v1/user") {
        const id = userIdFrom(request);
        if (!id) return send({ message: "invalid JWT" }, 401);
        return send({ id, aud: "authenticated", role: "authenticated", email: id === ADMIN_ID ? "admin@example.test" : "member@example.test", app_metadata: {}, user_metadata: {} });
      }

      // PostgREST reads
      if (method === "GET" && path === "/rest/v1/profiles") {
        const id = userIdFrom(request);
        const profile = { id, display_name: id === ADMIN_ID ? "Admin" : "Member", role: id === ADMIN_ID ? "admin" : "user", settings: {}, created_at: "2026-11-01T00:00:00Z" };
        return send(single ? profile : [profile]);
      }
      if (method === "GET" && path === "/rest/v1/reference_categories") return send(categories);
      if (method === "GET" && path === "/rest/v1/instruments") return send(instruments);
      if (method === "GET" && path === "/rest/v1/instrument_samples") return send(existingSamples);
      if (method === "GET" && path === "/rest/v1/reference_sounds") {
        if ((url.searchParams.get("select") ?? "").includes("reference_features")) {
          return send(
            references.map((r) => ({
              id: r.id,
              reference_categories: { slug: r.reference_categories!.slug },
              instrument_samples: r.instrument_samples && { midi_note: r.instrument_samples.midi_note, instruments: { slug: "piano" } },
              reference_features: [],
            })),
          );
        }
        const rows = url.searchParams.get("instrument_samples.instrument_id") ? references.filter((r) => r.instrument_samples) : references;
        return send(single ? rows[0] : rows, 200, rows.length);
      }

      // PostgREST writes
      if (method === "POST" && path === "/rest/v1/reference_sounds") {
        const row = JSON.parse(body) as Record<string, unknown>;
        log.push(`insert reference_sounds ${JSON.stringify(row)}`);
        const created = { id: `30000000-0000-4000-8000-${String(log.length).padStart(12, "0")}` };
        return send(single ? created : [created], 201);
      }
      if (method === "POST" && path === "/rest/v1/instrument_samples") {
        log.push(`insert instrument_samples ${body}`);
        return send(null, 201);
      }
      if (method === "POST" && path === "/rest/v1/reference_features") {
        const rows = JSON.parse(body) as Array<{ strategy_id: string; algorithm_version: string }>;
        log.push(`upsert reference_features ${rows.map((r) => `${r.strategy_id}@${r.algorithm_version}`).join(",")}`);
        return send(null, 201);
      }

      // Storage
      const signPrefix = "/storage/v1/object/upload/sign/references/";
      if (path.startsWith(signPrefix)) {
        const objectPath = decodeURIComponent(path.slice(signPrefix.length));
        if (method === "POST") {
          log.push(`sign ${objectPath}`);
          return send({ url: `/object/upload/sign/references/${objectPath}?token=test-token` });
        }
        if (method === "PUT") {
          // Browser uploads arrive as multipart form data; keep the WAV part.
          const start = raw.indexOf("RIFF");
          const boundary = (request.headers["content-type"] ?? "").split("boundary=")[1];
          const end = boundary ? raw.indexOf(`\r\n--${boundary}`, start) : raw.length;
          files.set(objectPath, raw.subarray(start, end > 0 ? end : raw.length));
          log.push(`upload ${objectPath}`);
          return send({ Key: `references/${objectPath}` });
        }
      }
      if (method === "GET" && path.startsWith("/storage/v1/object/references/")) {
        const file = files.get(decodeURIComponent(path.slice("/storage/v1/object/references/".length)));
        if (!file) return send({ error: "not found" }, 404);
        response.setHeader("content-type", "audio/wav");
        return response.end(file);
      }
      if (method === "POST" && path === "/storage/v1/object/sign/references") {
        const { paths = [] } = JSON.parse(body || "{}") as { paths?: string[] };
        return send(paths.map((p) => ({ path: p, signedURL: `/object/sign/references/${p}?token=test`, error: null })));
      }
      if (method === "DELETE" && path === "/storage/v1/object/references") {
        log.push(`remove ${body}`);
        return send([]);
      }

      send({ message: `fake-supabase: no route for ${method} ${path}` }, 404);
    });
  });
  server.listen(port);
  return server;
}

// Run directly: `tsx tests/e2e/support/fake-supabase.ts`
if (process.argv[1]?.endsWith("fake-supabase.ts")) {
  startFakeSupabase();
  console.log(`fake-supabase listening on ${FAKE_SUPABASE_PORT}`);
}
