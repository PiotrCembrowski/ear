/**
 * TEST-ONLY stand-in for the parts of Supabase (Auth, PostgREST, Storage)
 * that the signed-in pages use, so Playwright can exercise the library and
 * the admin importer without a real project. It understands just enough of
 * each API for these flows; it is NOT a general Supabase emulator and does
 * not enforce Row Level Security (that is tested against real Postgres in
 * tests/db and, in Phase 9, against a real project).
 *
 * Users are identified by the JWT "sub" in the session cookie (see session.ts):
 * ADMIN_ID has role "admin", MEMBER_ID has role "user".
 *
 * Started by playwright.config.ts on port 54399. GET /__log returns what was
 * written, and POST /__reset clears it, for assertions.
 */
